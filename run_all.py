"""Run the full GlobeFlex B analysis: data -> Steps 1-4 -> robustness -> output/results_summary.md.

Usage:  python run_all.py
"""
import time

import pandas as pd

from analysis import config as C
from analysis import data_prep, robustness, step1_dcc, step2_beta_tech, step3_crisis, step4_portfolio
from analysis import utils as U


def describe_data(raw, m, weekly, daily):
    U.save_table(m, "data_monthly_panel")
    rows = {"monthly returns": (m.index[0], m.index[-1], len(m)),
            "weekly returns (Step 1)": (weekly.index[0].date(), weekly.index[-1].date(), len(weekly)),
            "daily returns (event study)": (daily.index[0].date(), daily.index[-1].date(), len(daily))}
    tab = pd.DataFrame(rows, index=["first", "last", "observations"]).T
    tab["note"] = ["", "", f"MSCI data end {raw['END_DATE'].date()}"]
    U.save_table(tab, "data_samples")

    fig, ax = U.new_fig(figsize=(10, 3.2))
    ax.plot(m.index.to_timestamp(), 100 * m["W_IT"], color=U.SERIES[0], lw=1.8)
    ax.set_ylabel("% of MSCI EM market value", fontsize=9, color=U.INK_2)
    ax.set_title("IT weight in MSCI EM (w_IT = EM IT / EM market value), month end",
                 fontsize=11, color=U.INK, loc="left")
    U.save_fig(fig, "data_em_it_weight")
    return tab


def int_rows(df, rows):
    """Show count rows (N, months, weeks) as whole numbers."""
    df = df.astype(object)
    for r in rows:
        if r in df.index:
            df.loc[r] = [v if v != v else str(int(v)) for v in df.loc[r]]
    return df


def write_summary(data_tab, r1, r2, r3, r4, rob, m):
    reg = r2["regressions"].copy()
    reg["delta"] = reg.apply(lambda r: f"{r['delta']:.3f}{U.stars(r['p_delta'])}", axis=1)
    reg_cols = ["dependent", "interaction", "sample", "N", "beta", "delta", "t_delta", "R2"]
    rob_reg = rob["emsc_net"]["regressions"].copy()
    rob_reg["delta"] = rob_reg.apply(lambda r: f"{r['delta']:.3f}{U.stars(r['p_delta'])}", axis=1)

    count_rows = ["N", "Fin months, past", "Fin months, current", "Geo months, past", "Geo months, current"]

    def crisis_md(tab):
        return U.to_markdown(int_rows(tab, count_rows), "{:.3f}")

    def perf_md(tab):
        return U.to_markdown(int_rows(tab.T, ["months"]).T, "{:.2f}")

    lines = [
        "# GlobeFlex B - results summary",
        "",
        "Generated by `python run_all.py`. All returns are monthly log returns in % unless stated.",
        "Significance: * 10%, ** 5%, *** 1% (Newey-West).",
        "",
        "## Data",
        U.to_markdown(data_tab, "{}"),
        "",
        f"Crisis months in the monthly sample: Fin = {int(m['Fin'].sum())}, Geo = {int(m['Geo'].sum())}, "
        f"either = {int(m['Crisis'].sum())} of {len(m)}.",
        f"IT weight in MSCI EM: {100 * m['W_IT'].iloc[0]:.1f}% ({m.index[0]}) -> {100 * m['W_IT'].dropna().iloc[-1]:.1f}% "
        f"({m['W_IT'].dropna().index[-1]}).",
        "",
        "## Step 1 - DCC-GARCH(1,1) correlations (weekly)",
        U.to_markdown(int_rows(r1["dcc"], ["weeks"]), "{:.4f}"),
        "",
        "Average DCC correlation by year:",
        U.to_markdown(r1["annual"], "{:.2f}"),
        "",
        "![DCC](figures/step1_dcc_correlations.png)",
        "",
        "## Step 2 - Is EM more like the US, and is technology the cause?",
        f"Bai-Perron single break (EM on USA): last month of regime 1 = **{r2['break_month']}**, "
        f"Post_t = 1 from {r2['break_month'] + 1}. supF(1) = {r2['supF']:.2f} "
        f"(5% critical value {C.BP_SUPF_CV5}).",
        "",
        U.to_markdown(r2["bp"], "{:.4f}", index=False),
        "",
        "Equation (1): r_EM = alpha + beta r_US + delta (interaction x r_US). "
        "w_IT,t-1 is a fraction (0-1), so delta is the change in beta per 100 pp of IT weight.",
        "",
        U.to_markdown(reg[reg_cols], "{:.3f}", index=False),
        "",
        "## Step 3 - Crisis behaviour today versus the past",
        "Equation (2), dependent = EM (or EM ex-IT) minus World. Current = from 2018.",
        "",
        crisis_md(r3["coefs"]),
        "",
        "Daily event study: cumulative EM minus World (log %), from day -5.",
        "",
        U.to_markdown(r3["events"], "{:.2f}"),
        "",
        "Average by group:",
        "",
        U.to_markdown(r3["event_groups"], "{:.2f}"),
        "",
        "![Event study](figures/step3_event_study.png)",
        "",
        "## Step 4 - Portfolio evaluation (out of sample from 2006)",
        perf_md(r4["performance"]),
        "",
        "Weights are long-only minimum-variance weights from the previous 60 months. 'Geo months, past' is "
        "empty because all pre-2018 Geo months (2001-2005) fall before the 2006 out-of-sample start.",
        "",
        "![Portfolios](figures/step4_portfolios.png)",
        "",
        "## Robustness",
        "### 1. EM Small Cap net returns, post-2010",
        "DCC (weekly, post-2010):",
        "",
        U.to_markdown(rob["emsc_net"]["dcc"].astype({"weeks": int}), "{:.3f}"),
        "",
        "Equation (1), post-2010 months. The Post interaction is not estimable here: the break is "
        f"{r2['break_month']}, so Post_t = 1 in every post-2010 month (Post x r_US = r_US).",
        "",
        U.to_markdown(rob_reg[reg_cols], "{:.3f}", index=False),
        "",
        f"Portfolios, out of sample from {rob['emsc_net']['oos_start']}:",
        "",
        perf_md(rob["emsc_net"]["portfolio"]),
        "",
        "### 2. Local-currency EM returns (Step 3)",
        crisis_md(rob["local_ccy"]),
        "",
        "### 3. Current period from 2022 (Step 3)",
        crisis_md(rob["current_2022"]),
        "",
    ]
    (C.OUT_DIR / "results_summary.md").write_text("\n".join(lines))


def main():
    t0 = time.time()
    raw = data_prep.load_raw()
    m = data_prep.build_monthly(raw)
    weekly = data_prep.build_weekly(raw)
    daily = data_prep.build_daily(raw)
    data_tab = describe_data(raw, m, weekly, daily)
    print(f"data ready: {len(m)} months, {len(weekly)} weeks, {len(daily)} days")

    r1 = step1_dcc.run(weekly)
    print("step 1 done (DCC converged: %s)" % r1["converged"])
    r2 = step2_beta_tech.run(m)
    m = r2["panel"]                      # adds Post_t
    print(f"step 2 done (Bai-Perron break: {r2['break_month']})")
    r3 = step3_crisis.run(m, daily)
    print("step 3 done")
    r4 = step4_portfolio.run(m)
    print("step 4 done")
    rob = robustness.run(m, weekly)
    print("robustness done")
    U.save_table(m, "data_monthly_panel")
    write_summary(data_tab, r1, r2, r3, r4, rob, m)
    print(f"finished in {time.time() - t0:.0f}s -> {C.OUT_DIR}")


if __name__ == "__main__":
    main()
